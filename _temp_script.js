function fillForwardSets(sets){
  // if set 1 has a weight but sets 2/3 don't, carry set 1's weight forward as a
  // sensible prefill (most training uses the same weight across sets); an
  // explicitly recorded later set always wins and is left untouched
  const result = sets.map(s => ({ ...s }));
  let lastWt = null;
  result.forEach(s => {
    if(s.wt !== null){
      lastWt = s.wt;
    } else if(lastWt !== null){
      s.wt = lastWt;
    }
  });
  return result;
}

