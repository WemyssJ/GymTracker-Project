// Converts an entry from any earlier format (single-number Sam/Joe, or the
// hardcoded 3-set Sam/Joe format) into the generic { sets: { personId: [...] } }
// shape. Already-normalized entries are returned unchanged.
function normalizeEntry(e){
  if(e && e.sets) return e;
  const sets = {};
  if(e){
    if(e.samSets){
      sets.sam = e.samSets;
    } else if(typeof e.samWt === "number" || e.samNote){
      sets.sam = emptySets();
      sets.sam[0] = { wt: typeof e.samWt === "number" ? e.samWt : null, reps: e.samNote || "" };
    }
    if(e.joeSets){
      sets.joe = e.joeSets;
    } else if(typeof e.joeWt === "number" || e.joeNote){
      sets.joe = emptySets();
      sets.joe[0] = { wt: typeof e.joeWt === "number" ? e.joeWt : null, reps: e.joeNote || "" };
    }
  }
  return { sets };
}

function normalizeSessions(sessions){
  sessions.forEach(sess => {
    Object.keys(sess.entries).forEach(ex => {
      sess.entries[ex] = normalizeEntry(sess.entries[ex]);
    });
  });
  return sessions;
}

// Resolves old two-exercises-in-one-slot entries (e.g. "Tricep Push / Overhead Ext")
// into a single canonical exercise, for anyone whose phone still has data saved
// under the old merged names from an earlier version of this app.
const EXERCISE_SPLIT_RULES = {
  push: {
    "Dumbbell Press / Pec Fly": { newName: "Dumbbell Press", strip: /,?\s*pec fly [\d.]+kg/gi },
    "Tricep Push / Overhead Ext": { newName: "Tricep Push", strip: /,?\s*OH ext[^,]*/gi }
  },
  pull: {
    "Weighted Row / Lat Pull Down": { newName: "Weighted Row", strip: /,?\s*lat pulldown [\d.]+kg/gi },
    "Hammer Curl / Lat Raise": { newName: "Hammer Curl", swapFrom: /hammer curl ([\d.]+)kg/i }
  },
  leg: {
    "Leg Extension / Prone Leg Curl": { newName: "Prone Leg Curl", swapFrom: /prone leg curl ([\d.]+)kg/i }
  }
};

function extractWeightFromText(text, regex){
  if(!text) return null;
  const m = String(text).match(regex);
  return m ? parseFloat(m[1]) : null;
}

function stripFromText(text, regex){
  return String(text || "").replace(regex, "").replace(/^,\s*/, "").trim();
}

function migrateExerciseSplits(tabKey, sessions){
  const rules = EXERCISE_SPLIT_RULES[tabKey];
  if(!rules) return;
  sessions.forEach(sess => {
    Object.keys(rules).forEach(oldName => {
      const entry = sess.entries[oldName];
      if(!entry) return;
      const rule = rules[oldName];
      Object.keys(entry.sets || {}).forEach(personId => {
        const set0 = entry.sets[personId][0];
        if(!set0) return;
        if(rule.swapFrom){
          set0.wt = extractWeightFromText(set0.reps, rule.swapFrom);
          set0.reps = "";
        } else if(rule.strip){
          set0.reps = stripFromText(set0.reps, rule.strip);
        }
      });
      if(!sess.entries[rule.newName]){
        sess.entries[rule.newName] = entry;
      }
      delete sess.entries[oldName];
    });
  });
}

async function loadTab(tabKey){
  const cfg = CONFIG[tabKey];
  try{
    const raw = localStorage.getItem(cfg.key);
    const stored = raw ? JSON.parse(raw) : [];
    const storedDates = new Set(stored.map(s => s.date));
    const merged = [...stored];
    // add any seed sessions the phone doesn't already have, without touching
    // anything the user has actually logged for a date that matches
    cfg.seedHistory.forEach(seedSession => {
      if(!storedDates.has(seedSession.date)){
        merged.push(JSON.parse(JSON.stringify(seedSession)));
      }
    });
    merged.sort((a, b) => a.date.localeCompare(b.date));
    normalizeSessions(merged);
    migrateExerciseSplits(tabKey, merged);
    cache[tabKey] = merged;
    localStorage.setItem(cfg.key, JSON.stringify(merged));
  }catch(e){
    console.error("Storage read error", e);
    const fallback = cfg.seedHistory.map(s => JSON.parse(JSON.stringify(s)));
    normalizeSessions(fallback);
    migrateExerciseSplits(tabKey, fallback);
    cache[tabKey] = fallback;
  }
}

async function saveTab(tabKey){
  const cfg = CONFIG[tabKey];
  try{
    localStorage.setItem(cfg.key, JSON.stringify(cache[tabKey]));
  }catch(e){
    console.error("Storage write error", e);
    showToast("Couldn't save — storage may be full or blocked");
  }
}

function topSetWeight(sets){
  if(!sets) return null;
  const vals = sets.map(s => s.wt).filter(v => typeof v === "number");
  return vals.length ? Math.max(...vals) : null;
}

function computeStatsFor(tabKey, exercise, personId){
  const sessions = cache[tabKey];
  let best = null, last = null;
  for(const s of sessions){
    const e = s.entries[exercise];
    if(!e) continue;
    const top = topSetWeight(getPersonSets(e, personId));
    if(top !== null){
      if(best === null || top > best) best = top;
      last = top;
    }
  }
  return { best, last };
}

function getLastEntry(tabKey, exercise){
  const sessions = [...cache[tabKey]]
    .filter(s => s.entries[exercise])
    .sort((a, b) => b.date.localeCompare(a.date));
  return sessions.length ? sessions[0].entries[exercise] : null;
}

function getNextSessionType(){
  let nextKey = null, minDate = null;
  Object.keys(CONFIG).forEach(k => {
    const sessions = cache[k] || [];
    const lastDate = sessions.length
      ? sessions.reduce((max, s) => (s.date > max ? s.date : max), sessions[0].date)
      : ""; // never logged = most overdue
    if(minDate === null || lastDate < minDate){
      minDate = lastDate;
      nextKey = k;
    }
  });
  return nextKey;
}

