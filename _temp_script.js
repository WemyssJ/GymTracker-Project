function renderHistory(){
  const cfg = CONFIG[activeTab];
  const sessions = [...cache[activeTab]].sort((a,b)=> b.date.localeCompare(a.date));
  const container = document.getElementById("history");
  if(sessions.length === 0){
    container.innerHTML = '<div class="empty">No sessions logged yet.</div>';
    applyHistoryCollapsedState();
    return;
  }
  // precompute running bests in chronological order so we can flag PRs per row
  const chrono = [...cache[activeTab]].sort((a,b)=> a.date.localeCompare(b.date));
  const runningBest = {}; // ex -> personId -> best so far
  const prFlags = {}; // date|ex -> personId -> bool
  const regFlags = {};
  let prevRow = null;
  chrono.forEach(s=>{
    getExercises(activeTab).forEach(ex=>{
      const e = s.entries[ex];
      const flagKey = s.date + "|" + ex;
      if(!e){ return; }
      prFlags[flagKey] = {};
      regFlags[flagKey] = {};
      runningBest[ex] = runningBest[ex] || {};
      people.forEach(p=>{
        const top = topSetWeight(getPersonSets(e, p.id));
        if(top === null) return;
        const prevBest = runningBest[ex][p.id];
        prFlags[flagKey][p.id] = (prevBest === undefined || top >= prevBest);
        runningBest[ex][p.id] = Math.max(prevBest ?? -Infinity, top);
        const prevVal = prevRow && prevRow.entries[ex] ? topSetWeight(getPersonSets(prevRow.entries[ex], p.id)) : null;
        regFlags[flagKey][p.id] = (prevVal !== null && top < prevVal);
      });
    });
    prevRow = s;
  });

  container.innerHTML = "";
  sessions.slice(0,6).forEach(s=>{
    const row = document.createElement("div");
    row.className = "history-row";
    let inner = `
      <div class="hdate-row">
        <span class="hdate">${fmtDate(s.date)}</span>
        <button class="delete-btn" onclick="deleteSession('${activeTab}','${s.date}')" aria-label="Delete session">🗑</button>
      </div>
    `;
    getExercises(activeTab).forEach(ex=>{
      const e = s.entries[ex];
      if(!e) return;
      const flagKey = s.date + "|" + ex;
      const pf = prFlags[flagKey] || {};
      const rf = regFlags[flagKey] || {};
      let valsHtml = "";
      let setsHtml = "";
      people.forEach(p=>{
        const top = topSetWeight(getPersonSets(e, p.id));
        const display = top !== null ? top : "–";
        const cls = top !== null ? (pf[p.id] ? "pr-val" : (rf[p.id] ? "reg-val" : "")) : "";
        valsHtml += `<span class="${cls}">${display}</span>`;
        const summary = setsSummary(getPersonSets(e, p.id));
        if(summary){
          setsHtml += (setsHtml ? " · " : "") + `<span style="color:${p.color};font-weight:700;">${p.name}:</span> ${summary}`;
        }
      });
      inner += `
        <div class="hex">
          <span class="name">${ex}</span>
          <span class="vals">${valsHtml}</span>
        </div>
      `;
      if(setsHtml){
        inner += `<div class="hex-sets">${setsHtml}</div>`;
      }
    });
    row.innerHTML = inner;
    container.appendChild(row);
  });
  applyHistoryCollapsedState();
}

function setsSummary(sets){
  if(!sets) return "";
  return sets
    .filter(s => s.wt !== null || s.reps)
    .map(s => (s.wt !== null ? s.wt : "?") + (s.reps ? `x${s.reps}` : ""))
    .join(", ");
}

