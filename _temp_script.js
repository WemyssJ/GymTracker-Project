function renameExercise(tabKey, idx, newName){
  newName = newName.trim();
  if(!newName) return;
  const list = getExercises(tabKey);
  const oldName = list[idx];
  if(oldName === newName) return;
  if(list.includes(newName)){
    showToast("That exercise name is already used on this day");
    return;
  }
  list[idx] = newName;
  exercisesConfig[tabKey] = list;
  saveExercises();

  // carry historical data logged under the old name forward to the new name
  (cache[tabKey] || []).forEach(sess => {
    if(sess.entries[oldName] && !sess.entries[newName]){
      sess.entries[newName] = sess.entries[oldName];
      delete sess.entries[oldName];
    }
  });
  try{
    localStorage.setItem(CONFIG[tabKey].key, JSON.stringify(cache[tabKey] || []));
  }catch(e){
    console.error("Storage write error", e);
  }
  if(activeTab === tabKey){ renderStatStrip(); renderForm(); renderHistory(); }
}

