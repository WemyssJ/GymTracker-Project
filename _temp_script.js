async function pushToGithub(){
  const cfg = getGithubConfig();
  if(!cfg || !cfg.token || !cfg.repo){
    showToast("Set up GitHub first (tap ⚙)");
    openSettings();
    return;
  }

  const btn = document.getElementById("pushBtn");
  btn.disabled = true;
  btn.textContent = "Pushing…";

  try{
    // make sure every day's log is loaded, not just the active tab
    for(const k of Object.keys(CONFIG)){
      if(!cache[k]) await loadTab(k);
    }

    const localTotal = Object.keys(CONFIG).reduce((sum, k) => sum + (cache[k] || []).length, 0);
    if(localTotal === 0){
      if(!(await showConfirm("Your local log is empty. Pushing now could overwrite an existing GitHub backup with nothing. Continue?"))){
        btn.disabled = false;
        btn.textContent = "⤴ Push to GitHub";
        return;
      }
    }

    const payload = {
      push: cache.push || [],
      pull: cache.pull || [],
      leg: cache.leg || [],
      people: people,
      exportedAt: new Date().toISOString()
    };
    const content = utf8ToBase64(JSON.stringify(payload, null, 2));
    const apiUrl = `https://api.github.com/repos/${cfg.repo}/contents/${encodeURIComponent(cfg.path)}`;

    let sha;
    const getRes = await fetch(`${apiUrl}?ref=${encodeURIComponent(cfg.branch)}`, {
      headers: {
        Authorization: `Bearer ${cfg.token}`,
        Accept: "application/vnd.github+json"
      }
    });
    if(getRes.status === 200){
      const getJson = await getRes.json();
      sha = getJson.sha;

      // compare against what's already backed up before overwriting it
      try{
        const remoteJson = JSON.parse(base64ToUtf8(getJson.content));
        const remoteTotal = Object.keys(CONFIG).reduce((sum, k) => sum + (remoteJson[k] || []).length, 0);
        if(remoteTotal > 0 && localTotal < remoteTotal){
          const proceed = await showConfirm(
            `Your local log has ${localTotal} session${localTotal===1?"":"s"}, but GitHub currently has ${remoteTotal}. ` +
            `Pushing will overwrite the GitHub copy with less data. Continue anyway?`
          );
          if(!proceed){
            btn.disabled = false;
            btn.textContent = "⤴ Push to GitHub";
            return;
          }
        }
      }catch(parseErr){
        // existing file isn't in the expected format — skip the comparison, still allow the push
        console.warn("Couldn't parse existing GitHub file for comparison", parseErr);
      }
    } else if(getRes.status !== 404){
      const errJson = await getRes.json().catch(()=>({}));
      throw new Error(errJson.message || `Couldn't check existing file (${getRes.status})`);
    }

    const putBody = {
      message: `GymTracker log update — ${new Date().toLocaleString()}`,
      content,
      branch: cfg.branch
    };
    if(sha) putBody.sha = sha;

    const putRes = await fetch(apiUrl, {
      method: "PUT",
      headers: {
        Authorization: `Bearer ${cfg.token}`,
        Accept: "application/vnd.github+json",
        "Content-Type": "application/json"
      },
      body: JSON.stringify(putBody)
    });

    if(!putRes.ok){
      const errJson = await putRes.json().catch(()=>({}));
      throw new Error(errJson.message || `Push failed (${putRes.status})`);
    }

    showToast("Backed up to GitHub", "pr");
  }catch(e){
    console.error(e);
    showToast("GitHub push failed: " + e.message, "reg");
  }finally{
    btn.disabled = false;
    btn.textContent = "⤴ Push to GitHub";
  }
}

async function pullFromGithub(){
  const cfg = getGithubConfig();
  if(!cfg || !cfg.token || !cfg.repo){
    showToast("Set up GitHub first (tap ⚙)");
    openSettings();
    return;
  }

  const btn = document.getElementById("pullBtn");
  btn.disabled = true;
  btn.textContent = "Loading…";

  try{
    for(const k of Object.keys(CONFIG)){
      if(!cache[k]) await loadTab(k);
    }
    const localTotal = Object.keys(CONFIG).reduce((sum, k) => sum + (cache[k] || []).length, 0);

    const apiUrl = `https://api.github.com/repos/${cfg.repo}/contents/${encodeURIComponent(cfg.path)}`;
    const getRes = await fetch(`${apiUrl}?ref=${encodeURIComponent(cfg.branch)}`, {
      headers: {
        Authorization: `Bearer ${cfg.token}`,
        Accept: "application/vnd.github+json"
      }
    });

    if(getRes.status === 404){
      showToast("No backup found at that path on GitHub yet");
      return;
    }
    if(!getRes.ok){
      const errJson = await getRes.json().catch(()=>({}));
      throw new Error(errJson.message || `Couldn't fetch file (${getRes.status})`);
    }

    const getJson = await getRes.json();
    const remote = JSON.parse(base64ToUtf8(getJson.content));
    const remoteTotal = Object.keys(CONFIG).reduce((sum, k) => sum + (remote[k] || []).length, 0);

    if(localTotal > 0){
      const proceed = await showConfirm(
        `This device has ${localTotal} session${localTotal===1?"":"s"} saved. Loading from GitHub (${remoteTotal} session${remoteTotal===1?"":"s"}) will replace everything on this device. Continue?`
      );
      if(!proceed) return;
    }

    Object.keys(CONFIG).forEach(tabKey => {
      const sessions = Array.isArray(remote[tabKey]) ? remote[tabKey] : [];
      normalizeSessions(sessions);
      migrateExerciseSplits(tabKey, sessions);
      cache[tabKey] = sessions;
      try{ localStorage.setItem(CONFIG[tabKey].key, JSON.stringify(sessions)); }catch(e){}
    });

    if(Array.isArray(remote.people) && remote.people.length){
      people = remote.people;
      savePeople();
    }

    showToast("Loaded from GitHub", "pr");
    renderTabs();
    if(activeTab === "progress"){ renderProgressView(); }
    else if(activeTab === "settings"){ renderPeopleSettings(); renderExerciseSettings(); }
    else { renderStatStrip(); renderForm(); renderHistory(); }
  }catch(e){
    console.error(e);
    showToast("GitHub load failed: " + e.message, "reg");
  }finally{
    btn.disabled = false;
    btn.textContent = "⤵ Load from GitHub";
  }
}

