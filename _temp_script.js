function hexToRgb(hex){
  hex = hex.replace("#", "");
  if(hex.length === 3) hex = hex.split("").map(c => c + c).join("");
  const num = parseInt(hex, 16);
  return { r: (num >> 16) & 255, g: (num >> 8) & 255, b: num & 255 };
}

function rgbToHex({ r, g, b }){
  return "#" + [r, g, b].map(v => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, "0")).join("");
}

function mixHex(hex1, hex2, ratio){
  const c1 = hexToRgb(hex1), c2 = hexToRgb(hex2);
  return rgbToHex({
    r: c1.r + (c2.r - c1.r) * ratio,
    g: c1.g + (c2.g - c1.g) * ratio,
    b: c1.b + (c2.b - c1.b) * ratio
  });
}

function deriveTheme(bg, accent){
  return {
    bg,
    panel: mixHex(bg, "#ffffff", 0.06),
    panel2: mixHex(bg, "#ffffff", 0.11),
    line: mixHex(bg, "#ffffff", 0.19),
    text: mixHex(bg, "#ffffff", 0.92),
    muted: mixHex(bg, "#ffffff", 0.55),
    faint: mixHex(bg, "#ffffff", 0.38),
    accent,
    accentDim: mixHex(bg, accent, 0.28),
    accentInk: mixHex("#000000", accent, 0.12)
  };
}

