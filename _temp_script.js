async function handleSave(evt){
  evt.preventDefault();
  const cfg = CONFIG[activeTab];
  const date = document.getElementById("sessionDate").value;
  if(!date){ showToast("Pick a date first"); return; }

  function readSets(exIndex, personId){
    return [0, 1, 2].map(si => {
      const wtInput = document.querySelector(`[data-ex="${exIndex}"][data-person="${personId}"][data-set="${si}"][data-field="wt"]`);
      const repsInput = document.querySelector(`[data-ex="${exIndex}"][data-person="${personId}"][data-set="${si}"][data-field="reps"]`);
      const wtRaw = wtInput.value;
      return {
        wt: wtRaw === "" ? null : parseFloat(wtRaw),
        reps: repsInput.value
      };
    });
  }

  const entries = {};
  let prCount = 0, regCount = 0;
  let anyValue = false;
  getExercises(activeTab).forEach((ex, i)=>{
    const sets = {};
    people.forEach(p => {
      const personSets = readSets(i, p.id);
      sets[p.id] = personSets;

      if(personSets.some(s => s.wt !== null || s.reps.trim() !== "")){
        anyValue = true;
      }

      const top = topSetWeight(personSets);
      const st = computeStatsFor(activeTab, ex, p.id);
      if(top !== null){
        if(st.best !== null && top > st.best) prCount++;
        if(st.last !== null && top < st.last) regCount++;
      }
    });
    entries[ex] = { sets };
  });

  if(!anyValue){
    if(!(await showConfirm("Nothing's filled in — save an empty session anyway?"))){
      return;
    }
  }

  // remove any existing entry for the same date (overwrite instead of duplicate)
  cache[activeTab] = cache[activeTab].filter(s => s.date !== date);
  cache[activeTab].push({ date, entries });

  const saveBtn = document.getElementById("saveBtn");
  saveBtn.textContent = "Saving…";
  saveBtn.disabled = true;
  await saveTab(activeTab);
  saveBtn.disabled = false;

  renderTabs();
  renderStatStrip();
  renderForm();
  renderHistory();

  const ghCfg = getGithubConfig();
  const hasGithub = !!(ghCfg && ghCfg.token && ghCfg.repo);
  const savedPrefix = hasGithub ? "Saved" : "Saved locally";

  if(prCount > 0){
    showToast(`${savedPrefix} — ${prCount} new PR${prCount>1?"s":""} 🏆`, "pr");
  } else if(regCount > 0){
    showToast(`${savedPrefix} — down on ${regCount} lift${regCount>1?"s":""} from last time`, "reg");
  } else {
    showToast(hasGithub ? "Session saved" : "Session saved locally");
  }

  if(hasGithub){
    if(await showConfirm("Push this session to GitHub now?")){
      pushToGithub();
    }
  }
}

