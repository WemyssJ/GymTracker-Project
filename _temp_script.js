function exportExcel(){
  ensureAllLoaded().then(() => {
    if(typeof XLSX === "undefined"){
      showToast("Couldn't load the Excel library — check your connection");
      return;
    }
    const wb = XLSX.utils.book_new();
    Object.keys(CONFIG).forEach(tabKey => {
      const cfg = CONFIG[tabKey];
      const header = ["Date", "Exercise"];
      people.forEach(p => {
        for(let si = 1; si <= 3; si++){
          header.push(`${p.name} S${si} Wt`, `${p.name} S${si} Reps`);
        }
      });
      const rows = [header];
      const sessions = [...(cache[tabKey] || [])].sort((a, b) => a.date.localeCompare(b.date));
      sessions.forEach(sess => {
        getExercises(tabKey).forEach(ex => {
          const e = sess.entries[ex];
          if(!e) return;
          const row = [sess.date, ex];
          people.forEach(p => {
            getPersonSets(e, p.id).forEach(s => {
              row.push(s.wt !== null ? s.wt : "", s.reps || "");
            });
          });
          rows.push(row);
        });
      });
      const ws = XLSX.utils.aoa_to_sheet(rows);
      ws["!cols"] = [{ wch: 12 }, { wch: 30 }].concat(Array(people.length * 6).fill({ wch: 10 }));
      XLSX.utils.book_append_sheet(wb, ws, cfg.label + " Day");
    });

    // a People sheet so the backup can restore names/colors on another device too
    const peopleRows = [["id", "name", "color"], ...people.map(p => [p.id, p.name, p.color])];
    const peopleWs = XLSX.utils.aoa_to_sheet(peopleRows);
    XLSX.utils.book_append_sheet(wb, peopleWs, "People");

    XLSX.writeFile(wb, `GymTracker-backup-${todayStr()}.xlsx`);
    showToast("Backup downloaded");
  });
}

function handleImportFile(event){
  const file = event.target.files[0];
  if(!file) return;
  if(typeof XLSX === "undefined"){
    showToast("Couldn't load the Excel library — check your connection");
    return;
  }
  const reader = new FileReader();
  reader.onload = async (e) => {
    try{
      const data = new Uint8Array(e.target.result);
      const wb = XLSX.read(data, { type: "array" });
      await ensureAllLoaded();

      // work out which file-person maps to which currently-configured person
      let filePeople = null;
      if(wb.Sheets["People"]){
        const rows = XLSX.utils.sheet_to_json(wb.Sheets["People"], { header: 1 }).slice(1);
        filePeople = rows.filter(r => r && r[0]).map(r => ({ id: String(r[0]), name: String(r[1] || r[0]), color: r[2] || "" }));
      }

      let idMap = {};
      if(filePeople && filePeople.length){
        const sameIds = filePeople.every(fp => people.some(p => p.id === fp.id));
        let adopted = false;
        if(!sameIds){
          const fileNames = filePeople.map(p => p.name).join(", ");
          const replace = await showConfirm(
            `This backup was made with different people (${fileNames}). Replace your current people list with theirs? ` +
            `Choosing Cancel keeps your current people and matches by name where possible.`
          );
          if(replace){
            people = filePeople.map((p, idx) => ({
              id: p.id, name: p.name, color: p.color || COLOR_PALETTE[idx % COLOR_PALETTE.length]
            }));
            savePeople();
            adopted = true;
          }
        }
        if(adopted){
          filePeople.forEach(fp => { idMap[fp.id] = fp.id; });
        } else {
          filePeople.forEach(fp => {
            const match = people.find(p => p.name === fp.name);
            if(match) idMap[fp.id] = match.id;
          });
        }
      } else {
        // legacy backup with no People sheet — assume the old fixed Sam/Joe layout
        const match = name => people.find(p => p.name === name);
        const sam = match("Sam"), joe = match("Joe");
        if(sam) idMap["sam"] = sam.id;
        if(joe) idMap["joe"] = joe.id;
      }

      let importedRows = 0;
      const skippedPeople = new Set();

      Object.keys(CONFIG).forEach(tabKey => {
        const cfg = CONFIG[tabKey];
        const sheetName = cfg.label + " Day";
        const ws = wb.Sheets[sheetName];
        if(!ws) return;

        const aoa = XLSX.utils.sheet_to_json(ws, { header: 1 });
        const header = aoa[0] || [];
        const byDate = new Map((cache[tabKey] || []).map(s => [s.date, s]));
        const numOrNull = v => (v === "" || v === undefined || v === null || isNaN(parseFloat(v))) ? null : parseFloat(v);

        const peopleColumns = filePeople && filePeople.length
          ? filePeople.map(fp => ({ filePerson: fp, startIdx: header.indexOf(`${fp.name} S1 Wt`) })).filter(pc => pc.startIdx !== -1)
          : [
              { filePerson: { id: "sam", name: "Sam" }, startIdx: 2 },
              { filePerson: { id: "joe", name: "Joe" }, startIdx: 8 }
            ];

        aoa.slice(1).forEach(row => {
          if(!row || !row[0] || !row[1]) return;
          const rawDate = row[0];
          const date = rawDate instanceof Date
            ? rawDate.toISOString().slice(0, 10)
            : String(rawDate).slice(0, 10);
          const exercise = String(row[1]);
          if(!getExercises(tabKey).includes(exercise)) return;

          if(!byDate.has(date)) byDate.set(date, { date, entries: {} });
          if(!byDate.get(date).entries[exercise]) byDate.get(date).entries[exercise] = { sets: {} };
          const entrySets = byDate.get(date).entries[exercise].sets;

          peopleColumns.forEach(pc => {
            const targetId = idMap[pc.filePerson.id];
            if(!targetId){ skippedPeople.add(pc.filePerson.name); return; }
            entrySets[targetId] = [0, 1, 2].map(si => ({
              wt: numOrNull(row[pc.startIdx + si * 2]),
              reps: row[pc.startIdx + si * 2 + 1] || ""
            }));
            importedRows++;
          });
        });

        const merged = [...byDate.values()].sort((a, b) => a.date.localeCompare(b.date));
        cache[tabKey] = merged;
        localStorage.setItem(cfg.key, JSON.stringify(merged));
      });

      if(importedRows === 0){
        showToast("No matching data found in that file");
      } else {
        const skippedMsg = skippedPeople.size ? ` (skipped: ${[...skippedPeople].join(", ")})` : "";
        showToast(`Restored ${importedRows} entries${skippedMsg}`);
        renderTabs();
        if(activeTab === "progress"){ renderProgressView(); }
        else if(activeTab === "settings"){ renderPeopleSettings(); }
        else { renderStatStrip(); renderForm(); renderHistory(); }
      }
    }catch(err){
      console.error(err);
      showToast("Couldn't read that file: " + err.message);
    }
  };
  reader.readAsArrayBuffer(file);
  event.target.value = "";
}

