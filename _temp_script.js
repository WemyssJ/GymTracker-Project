function drawLineChart(series){
  const canvas = document.getElementById("progressCanvas");
  const dpr = window.devicePixelRatio || 1;
  const cssWidth = canvas.parentElement.clientWidth;
  const cssHeight = 300;
  canvas.style.width = cssWidth + "px";
  canvas.style.height = cssHeight + "px";
  canvas.width = cssWidth * dpr;
  canvas.height = cssHeight * dpr;
  const ctx = canvas.getContext("2d");
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.clearRect(0, 0, cssWidth, cssHeight);

  if(series.length === 0){
    ctx.fillStyle = "#7d94a1";
    ctx.font = "13px -apple-system, sans-serif";
    ctx.textAlign = "center";
    ctx.textBaseline = "middle";
    ctx.fillText("No sessions logged for this exercise yet", cssWidth / 2, cssHeight / 2);
    return;
  }

  const paddingLeft = 34, paddingRight = 14, paddingTop = 16, paddingBottom = 66;
  const chartW = cssWidth - paddingLeft - paddingRight;
  const chartH = cssHeight - paddingTop - paddingBottom;
  const baseY = paddingTop + chartH;

  const allVals = series.flatMap(pt => people.map(p => pt.values[p.id])).filter(v => typeof v === "number");
  const maxVal = Math.max(1, ...allVals);
  const niceMax = Math.ceil(maxVal / 10) * 10 || 10;

  ctx.strokeStyle = "#2f4049";
  ctx.fillStyle = "#7d94a1";
  ctx.font = "11px -apple-system, sans-serif";
  ctx.textAlign = "right";
  ctx.textBaseline = "middle";
  const steps = 4;
  for(let i = 0; i <= steps; i++){
    const val = (niceMax / steps) * i;
    const y = baseY - (val / niceMax) * chartH;
    ctx.beginPath();
    ctx.moveTo(paddingLeft, y);
    ctx.lineTo(paddingLeft + chartW, y);
    ctx.stroke();
    ctx.fillText(Math.round(val), paddingLeft - 6, y);
  }

  const n = series.length;
  const xStep = n > 1 ? chartW / (n - 1) : 0;
  const xPos = i => paddingLeft + (n > 1 ? i * xStep : chartW / 2);

  function drawSeries(personId, color){
    ctx.strokeStyle = color;
    ctx.fillStyle = color;
    ctx.lineWidth = 2.5;
    let drawing = false;
    series.forEach((pt, i) => {
      const val = pt.values[personId];
      const x = xPos(i);
      if(typeof val === "number"){
        const y = baseY - (val / niceMax) * chartH;
        if(!drawing){ ctx.beginPath(); ctx.moveTo(x, y); drawing = true; }
        else { ctx.lineTo(x, y); }
      } else if(drawing){
        ctx.stroke();
        drawing = false;
      }
    });
    if(drawing) ctx.stroke();
    series.forEach((pt, i) => {
      const val = pt.values[personId];
      if(typeof val === "number"){
        const x = xPos(i);
        const y = baseY - (val / niceMax) * chartH;
        ctx.beginPath();
        ctx.arc(x, y, 3.2, 0, Math.PI * 2);
        ctx.fill();
      }
    });
  }

  people.forEach(p => drawSeries(p.id, p.color));

  ctx.fillStyle = "#7d94a1";
  ctx.font = "10px -apple-system, sans-serif";
  series.forEach((pt, i) => {
    const x = xPos(i);
    ctx.save();
    ctx.translate(x, baseY + 8);
    ctx.rotate(-Math.PI / 4);
    ctx.textAlign = "right";
    ctx.textBaseline = "middle";
    const d = new Date(pt.date + "T00:00:00");
    ctx.fillText(d.toLocaleDateString(undefined, { day: "numeric", month: "short" }), 0, 0);
    ctx.restore();
  });

  ctx.strokeStyle = "#3d5561";
  ctx.beginPath();
  ctx.moveTo(paddingLeft, baseY);
  ctx.lineTo(paddingLeft + chartW, baseY);
  ctx.stroke();
}

